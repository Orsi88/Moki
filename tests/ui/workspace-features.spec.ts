import { test, expect, type ElectronApplication } from '@playwright/test';
import { cpSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { ROOT } from '../../scripts/lib/repo.mjs';
import { buildDocx } from '../../scripts/docx.mjs';
import { buildXlsx } from '../../scripts/xlsx.mjs';
import { wordDocument } from '../../scripts/lib/office-word.ts';
import { workbookInfo } from '../../scripts/lib/office-sheet.ts';
import { launchMoki } from './launch.ts';

test('native Office edits/comments, runnable isolated HTML and the IDE rail shortcut work in the desktop app', async () => {
  const root = mkdtempSync(join(tmpdir(), 'moki-features-')), profile = mkdtempSync(join(tmpdir(), 'moki-features-profile-'));
  const project = join(root, 'workspace', 'projects', 'acme'), inbox = join(project, 'inbox');
  let app: ElectronApplication | undefined;
  try {
    writeFileSync(join(root, 'package.json'), JSON.stringify({ version: '0.0.0-test' }));
    for (const dir of ['skills', 'agents', 'activities', 'templates']) cpSync(join(ROOT, dir), join(root, dir), { recursive: true });
    cpSync(join(ROOT, 'templates', 'project-context'), project, { recursive: true });
    const config = JSON.parse(readFileSync(join(project, 'project.json'), 'utf8'));
    writeFileSync(join(project, 'project.json'), JSON.stringify({ ...config, project: 'acme', name: 'Workspace features' }));
    mkdirSync(inbox, { recursive: true });
    writeFileSync(join(inbox, 'styled.docx'), buildDocx({ blocks: [{ type: 'heading', level: 1, text: 'Original heading' }, { type: 'paragraph', text: 'Original paragraph', bold: true }] }).buffer);
    writeFileSync(join(inbox, 'styled.xlsx'), buildXlsx({ sheets: [{ key: 'data', title: 'Data', columns: [{ key: 'name', label: 'Name' }, { key: 'value', label: 'Value' }] }] }, { data: Array.from({ length: 300 }, (_, index) => ({ name: index === 0 ? 'Original' : 'Row ' + index, value: '42' })) }));
    writeFileSync(join(inbox, 'legacy.doc'), 'Legacy fixture');
    writeFileSync(join(inbox, 'index.html'), '<link rel="stylesheet" href="style.css"><h1>Demo</h1><button id="counter">Count 0</button><p id="module"></p><script type="module" src="app.js"></script>');
    writeFileSync(join(inbox, 'style.css'), 'h1 { color: rgb(12, 34, 56); }');
    writeFileSync(join(inbox, 'data.json'), '{"label":"Modules and fetch work"}');
    writeFileSync(join(inbox, 'app.js'), 'const data = await fetch("./data.json").then(r=>r.json()); document.querySelector("#module").textContent=data.label; let n=0;document.querySelector("#counter").onclick=e=>e.target.textContent="Count "+(++n);');
    app = await launchMoki({ QA_ROOT: root, QA_USER_DATA: profile, QA_OPEN_PROJECT: 'acme', QA_FAKE_TOOLS: '1' });
    const view = await app.firstWindow();
    await view.evaluate(() => localStorage.setItem('qa-ui-language', 'en')); await view.reload();
    const errors: string[] = []; view.on('pageerror', e => errors.push(e.message));
    await view.getByRole('button', { name: 'Moki in your IDE', exact: true }).click();
    await expect(view.getByRole('dialog', { name: 'Moki in your IDE' })).toBeVisible();
    await expect(view.getByRole('button', { name: /^Open Moki in VS Code/ })).toBeEnabled();
    await expect(view.locator('.ide-shortcut-row button')).toHaveText(['Open', 'Open']);
    await view.keyboard.press('Escape');
    await expect(view.locator('.ribbon .ribbon-ide + .ribbon-note')).toHaveCount(1);
    await expect(view.locator('.ribbon-ide svg path').first()).toHaveAttribute('d', 'M12 19c-4.4 0-7.5-1.6-7.5-4.7 0-1.3.4-2.5 1.1-3.4l-.5-4.7a.8.8 0 0 1 1.3-.7l3.4 2.6a8.6 8.6 0 0 1 4.4 0l3.4-2.6a.8.8 0 0 1 1.3.7l-.5 4.7c.7.9 1.1 2.1 1.1 3.4 0 3.1-3.1 4.7-7.5 4.7Z');
    await expect(view.locator('.pp-ide')).toHaveCount(0);
    await view.getByRole('button', { name: 'New: terminal, AI or file', exact: true }).click();
    await expect(view.getByRole('menuitem', { name: 'Moki in your IDE' })).toHaveCount(0); await view.keyboard.press('Escape');
    await view.locator('.tree-row[title="inbox"]').click();
    await view.locator('.tree-row[title="inbox/styled.docx"]').click();
    await expect(view.locator('.office-comments')).toHaveCount(0);
    await expect(view.locator('.office-editor-bar')).toHaveCount(0);
    await expect(view.locator('.doc-actions [role="status"]')).toHaveText('Saved');
    await view.getByRole('button', { name: 'Comments', exact: true }).click();
    const paragraph = view.getByRole('textbox', { name: 'Paragraph 2', exact: true });
    await expect(paragraph).toHaveText('Original paragraph');
    await expect(paragraph.locator('span').first()).toHaveCSS('font-weight', '700');
    await paragraph.fill('Edited in Moki'); await paragraph.press('Tab');
    await expect.poll(() => wordDocument(readFileSync(join(inbox, 'styled.docx'))).paragraphs[1].text).toBe('Edited in Moki');
    await view.getByPlaceholder('Write a comment…').fill('Word native comment');
    await view.getByRole('button', { name: 'Add comment', exact: true }).click();
    await expect.poll(() => wordDocument(readFileSync(join(inbox, 'styled.docx'))).comments[0]?.text).toBe('Word native comment');
    await view.locator('.tree-row[title="inbox/styled.xlsx"]').click();
    const cell = view.locator('td[data-cell="B2"]'); await cell.click();
    await expect(view.getByRole('button', { name: 'Show more rows' })).toHaveCount(0);
    await view.locator('.office-sheet-grid').dispatchEvent('wheel', { deltaY: -120, ctrlKey: true });
    await expect(view.getByRole('button', { name: 'Reset zoom' })).toHaveText('110%');
    await view.getByRole('button', { name: 'Reset zoom' }).click();
    const formula = view.getByRole('textbox', { name: 'Cell value or formula' });
    await expect(formula).toHaveValue('42'); await formula.fill('73.5'); await formula.press('Enter');
    await expect.poll(() => workbookInfo(readFileSync(join(inbox, 'styled.xlsx'))).sheets[0].cells.B2.value).toBe('73.5');
    await view.getByPlaceholder('Write a comment…').fill('Excel native note');
    await view.getByRole('button', { name: 'Add comment', exact: true }).click();
    await expect.poll(() => workbookInfo(readFileSync(join(inbox, 'styled.xlsx'))).sheets[0].comments[0]?.text).toBe('Excel native note');
    await view.locator('td[data-cell="D10"]').click();
    await view.locator('.office-comments article').getByText('Excel native note', { exact: true }).click();
    await expect(view.locator('td[data-cell="B2"]')).toHaveAttribute('aria-selected', 'true');
    await expect(view.locator('.office-comments article .comment-actions')).toHaveCount(1);
    await expect(view.locator('.office-comments article .office-comment-head button')).toHaveCount(0);
    await view.locator('.office-sheet-grid').evaluate(element => { element.scrollTop = element.scrollHeight; element.dispatchEvent(new Event('scroll')); });
    await expect(view.locator('td[data-cell="A250"]')).toHaveCount(1);
    await view.getByRole('button', { name: 'Close comments', exact: true }).click();
    await expect(view.locator('.office-comments')).toHaveCount(0);
    await view.locator('.tree-row[title="inbox/legacy.doc"]').click();
    await expect(view.getByRole('button', { name: 'Convert and edit a copy' })).toBeVisible();
    await view.locator('.tree-row[title="inbox/index.html"]').click();
    await expect(view.locator('.doc-bar .html-preview-bar')).toHaveCount(1);
    await expect(view.locator('.html-preview > .html-preview-bar')).toHaveCount(0);
    await expect(view.getByRole('button', { name: 'Reload this file' })).toHaveCount(0);
    const frame = view.frameLocator('iframe[title="inbox/index.html"]');
    await expect(frame.locator('#module')).toHaveText('Modules and fetch work');
    await expect(frame.locator('h1')).toHaveCSS('color', 'rgb(12, 34, 56)');
    await frame.getByRole('button', { name: 'Count 0' }).click(); await expect(frame.locator('#counter')).toHaveText('Count 1');
    const child = view.frames().find(frame => frame.url().startsWith('moki-preview:'))!;
    expect(await child.evaluate(() => ({ bridge: typeof (window as unknown as { qa?: unknown }).qa, node: typeof (globalThis as unknown as { require?: unknown }).require, parent: (() => { try { return Boolean(parent.document); } catch { return false; } })() }))).toEqual({ bridge: 'undefined', node: 'undefined', parent: false });
    const reload = view.getByRole('button', { name: 'Reload preview' });
    await expect(reload).toHaveText('');
    await expect(view.getByRole('button', { name: 'Open in browser' })).toHaveText('');
    const heights = await view.locator('.html-preview-bar select, .html-preview-bar button').evaluateAll(elements => elements.map(element => element.getBoundingClientRect().height));
    expect(heights).toEqual([30, 30, 30, 30]);
    await view.getByLabel('Preview width').selectOption('390px');
    await expect(view.locator('iframe[title="inbox/index.html"]')).toHaveCSS('width', '390px');
    await view.getByRole('button', { name: 'Reload preview' }).click(); await expect(frame.locator('#counter')).toHaveText('Count 0');
    const sourceBeforeComment = readFileSync(join(inbox, 'index.html'), 'utf8');
    await view.getByRole('button', { name: 'Comments', exact: true }).click();
    await frame.locator('h1').evaluate(element => { const range = document.createRange(); range.selectNodeContents(element); const selected = document.getSelection()!; selected.removeAllRanges(); selected.addRange(range); element.dispatchEvent(new MouseEvent('mouseup', { bubbles: true })); });
    const htmlComments = view.locator('.html-comments');
    await expect(htmlComments.locator('blockquote')).toHaveText('Demo');
    await htmlComments.getByPlaceholder('Write a comment…').fill('Review the demo heading');
    await htmlComments.getByRole('button', { name: 'Add comment', exact: true }).click();
    await expect(htmlComments.locator('article')).toContainText('Review the demo heading');
    expect(readFileSync(join(inbox, 'index.html'), 'utf8')).toBe(sourceBeforeComment);
    await view.getByRole('button', { name: 'Reload preview' }).click();
    await expect(htmlComments.locator('article')).toContainText('Review the demo heading');
    await expect(frame.locator('#module')).toHaveText('Modules and fetch work');
    await htmlComments.getByRole('button', { name: 'Go to the commented location' }).click();
    await expect(frame.locator('h1')).toBeInViewport();
    await expect(htmlComments.locator('article .comment-actions button')).toHaveCount(2);
    await htmlComments.getByRole('button', { name: 'Delete comment' }).click();
    await expect(htmlComments.locator('article')).toHaveCount(0);
    expect(errors).toEqual([]);
  } finally { await app?.close(); rmSync(root, { recursive: true, force: true }); rmSync(profile, { recursive: true, force: true }); }
});
