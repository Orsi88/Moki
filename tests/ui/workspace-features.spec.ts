async function selectPassage(element: Locator, start: number, end: number) {
  await element.evaluate((root, offsets) => {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT), range = document.createRange();
    let at = 0, started = false;
    for (let node = walker.nextNode(); node; node = walker.nextNode()) {
      const length = node.textContent?.length ?? 0;
      if (!started && offsets.start >= at && offsets.start < at + length) { range.setStart(node, offsets.start - at); started = true; }
      if (started && offsets.end <= at + length) { range.setEnd(node, offsets.end - at); break; }
      at += length;
    }
    const selection = document.getSelection();
    selection?.removeAllRanges(); selection?.addRange(range);
    root.dispatchEvent(new MouseEvent('mouseup', { bubbles: true }));
  }, { start, end });
}

async function expectJoined(stage: Locator, anchor: string) {
  await expect.poll(() => stage.evaluate((root, selector) => {
    const passage = root.querySelector(selector)?.getBoundingClientRect(), card = root.querySelector('[data-card]')?.getBoundingClientRect();
    if (!passage || !card) return 10000;
    return Math.abs(card.top + 18 - (passage.top + passage.height / 2));
  }, anchor)).toBeLessThan(6);
}


